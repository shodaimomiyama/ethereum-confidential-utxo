import { readFileSync, writeFileSync } from 'node:fs';
import { artifactPath as poolArtifactPath, outputPath as poolRecordPath, verifyPoolRecord } from './pool-artifact.mjs';
import { artifactPath as verifierArtifactPath, outputPath as verifierRecordPath,
  verifyVerifierRecord, constructorArgs } from './verifier-artifact.mjs';
import { artifactPath as adapterArtifactPath, outputPath as adapterRecordPath,
  verifyUniswapPaymentRecord } from './uniswap-payment-artifact.mjs';

const load = path => JSON.parse(readFileSync(path, 'utf8'));
const pool = verifyPoolRecord(load(poolRecordPath), load(poolArtifactPath));
const verifier = verifyVerifierRecord(load(verifierRecordPath), load(verifierArtifactPath));
const adapter = verifyUniswapPaymentRecord(load(adapterRecordPath), load(adapterArtifactPath));
const pay = adapter.abi.filter(item => item.type === 'function' && item.name === 'pay');
if (pay.length !== 1 || pay[0].stateMutability !== 'nonpayable') throw new Error('Adapter pay ABI mismatch');
const path = 'packages/ethereum/src/abi.ts';
const source = `// Generated by scripts/export-ethereum-abi.mjs from verified Foundry artifact records.\n` +
  `export const poolAbi = ${JSON.stringify(pool.abi)} as const;\n` +
  `export const verifierAbi = ${JSON.stringify(verifier.abi)} as const;\n` +
  `export const uniswapPayAbi = ${JSON.stringify(pay)} as const;\n`;
let previous = '';
try { previous = readFileSync(path, 'utf8'); } catch (error) {
  if (error.code !== 'ENOENT') throw error;
}
if (previous !== source) writeFileSync(path, source);
const artifactPath = 'packages/ethereum/src/artifacts.ts';
const artifacts = `// Generated by scripts/export-ethereum-abi.mjs from verified Foundry artifact records.\n` +
  `export const poolArtifact = ${JSON.stringify({
    creationBytecode: pool.creationBytecode,
    runtimeBytecode: pool.runtimeBytecode,
    immutableReferences: Object.values(pool.immutableReferences).flat(),
    runtimeSha256: pool.manifest.runtimeSha256,
  })} as const;\n` +
  `export const verifierArtifact = ${JSON.stringify({
    creationBytecode: verifier.creationBytecode,
    runtimeBytecode: verifier.runtimeBytecode,
    constructorArgs: constructorArgs(),
    runtimeSha256: verifier.manifest.runtimeSha256,
    parametersHash: verifier.parametersHash,
  })} as const;\n`;
let oldArtifacts = '';
try { oldArtifacts = readFileSync(artifactPath, 'utf8'); } catch (error) {
  if (error.code !== 'ENOENT') throw error;
}
if (oldArtifacts !== artifacts) writeFileSync(artifactPath, artifacts);
