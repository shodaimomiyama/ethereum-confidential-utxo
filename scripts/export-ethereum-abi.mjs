import { readFileSync, writeFileSync } from 'node:fs';
import { artifactPath as poolArtifactPath, outputPath as poolRecordPath, verifyPoolRecord } from './pool-artifact.mjs';
import { artifactPath as verifierArtifactPath, outputPath as verifierRecordPath,
  verifyVerifierRecord } from './verifier-artifact.mjs';

const load = path => JSON.parse(readFileSync(path, 'utf8'));
const pool = verifyPoolRecord(load(poolRecordPath), load(poolArtifactPath));
const verifier = verifyVerifierRecord(load(verifierRecordPath), load(verifierArtifactPath));
const path = 'packages/ethereum/src/abi.ts';
const source = `// Generated by scripts/export-ethereum-abi.mjs from verified Foundry artifact records.\n` +
  `export const poolAbi = ${JSON.stringify(pool.abi)} as const;\n` +
  `export const verifierAbi = ${JSON.stringify(verifier.abi)} as const;\n`;
let previous = '';
try { previous = readFileSync(path, 'utf8'); } catch (error) {
  if (error.code !== 'ENOENT') throw error;
}
if (previous !== source) writeFileSync(path, source);
